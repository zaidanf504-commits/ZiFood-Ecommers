<?php

namespace App\Http\Controllers;

use App\Models\User;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Facades\Hash;

class AuthController extends Controller
{
    public function showLogin() { return view('auth.login'); }
    public function showRegister() { return view('auth.register'); }

    public function register(Request $request)
    {
        $request->validate([
            'name' => 'required|string|max:255',
            'email' => 'required|string|email|max:255|unique:users',
            'password' => 'required|string|min:8|confirmed',
            'role' => 'required|in:penjual,pembeli',
        ]);

        $user = User::create([
            'name' => $request->name,
            'email' => $request->email,
            'password' => Hash::make($request->password),
            'role' => $request->role,
        ]);

        Auth::login($user);

        // Redirect otomatis setelah daftar sesuai role
        return $user->role === 'penjual' 
            ? redirect()->route('seller.dashboard') 
            : redirect()->route('dashboard');
    }

    // Update di app/Http/Controllers/AuthController.php
public function login(Request $request)
{
    $credentials = $request->validate([
        'email' => 'required|email',
        'password' => 'required',
    ]);

    if (Auth::attempt($credentials)) {
        $request->session()->regenerate();
        
        // PENGALIEHAN SESUAI ROLE
        if (Auth::user()->role === 'penjual') {
            return redirect()->intended('/seller/dashboard'); // Ke Dashboard Penjual
        }
        
        return redirect()->intended('/dashboard'); // Ke Katalog Pembeli
    }

    return back()->withErrors(['email' => 'Data login salah!']);
}

    public function logout(Request $request)
    {
        Auth::logout();
        $request->session()->invalidate();
        $request->session()->regenerateToken();
        return redirect('/');
    }
}